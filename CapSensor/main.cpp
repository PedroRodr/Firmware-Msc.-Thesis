void initClockTo1MHz()
{
    if (CALBC1_1MHZ==0xFF)                             // If calibration constant erased
    {
        while(1);                                       // do not load, trap CPU!!
    }
    DCOCTL = 0;                                         // Select lowest DCOx and MODx settings
    BCSCTL1 = CALBC1_1MHZ;                             // Set DCO
    DCOCTL = CALDCO_1MHZ;
}
void Pin1_5_int()
{
    P1IE |= 0x20;                                       // P1.5 interrupt enabled
    P1IES |= 0x20;                                      // P1.5 Hi/lo edge
    P1IFG &= ~0x20;                                     // P1.5 IFG cleared
}
//**********************************************************************************************************************************
// Header: main
// Function: Entry point
//**********************************************************************************************************************************
int main(void){

    WDTCTL = WDTPW + WDTHOLD;                           // Stop WDT

    initClockTo1MHz();
    Pin1_5_int();
    P1SEL = BIT1 + BIT2  + BIT6 + BIT7;   //Bits 1 e 2 da Serial 6,7 do I2C
    P1SEL2 = BIT1 + BIT2 + BIT6 + BIT7;   //Bits 1 e 2 da Serial 6,7 do I2C
    Serial::init();
    I2C::init();

    __bis_SR_register(GIE);

    while(1){

        // keep sending measurements and checking for cmds!
        Interface::runStateMachine();
    }
}
